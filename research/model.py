#!/usr/bin/env python3
"""Learn hourly ride demand from Chicago tracts and transfer it to Seattle-area tracts.

Reads research/data/ (written by pull.py). Writes research/out/:
  signatures.csv      rides per hour generated by each kind of place, by day type and hour (NNLS)
  cv.json             spatial cross-validation of the predictive model on Chicago
  seattle_pred.csv.gz predicted pickups/hour and airport share per Seattle-area tract x day type x hour

Two models, on purpose:
  * an interpretable one (non-negative least squares): pickups(tract, hour) ~ sum_k count_k(tract) * beta_k(hour),
    so beta_k(hour) is "rides per hotel / per bar / per 1,000 jobs ... at this hour" - the hourly signature of
    each kind of place;
  * a predictive one (gradient-boosted trees) on the same features plus neighbourhood traits, validated by
    holding out whole Chicago community areas, then applied to Seattle tracts.
"""
import csv
import gzip
import json
import math
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.optimize import nnls

ROOT = Path(__file__).resolve().parent
DATA, OUT = ROOT / "data", ROOT / "out"
DAYTYPES = {"mon_thu": [1, 2, 3, 4], "fri": [5], "sat": [6], "sun": [0]}  # Socrata dow: 0 = Sunday
CENTER = {"chicago": (41.8827, -87.6233), "seattle": (47.6097, -122.3410)}
AIRPORT = {"chicago": (41.9786, -87.9048), "seattle": (47.4502, -122.3088)}

# kinds of places whose hourly signature we estimate (column -> label)
GENERATORS = {
    "osm_hotel": "hotel", "osm_bar": "bar/pub", "osm_nightclub": "nightclub", "osm_restaurant": "restaurant",
    "osm_venue": "theatre/venue", "osm_hospital": "hospital", "osm_university": "university",
    "osm_rail_station": "rail station", "jobs_k": "1,000 jobs", "pop_k": "1,000 residents",
}


def km(a, b):
    R = 6371.0
    la1, lo1, la2, lo2 = map(math.radians, (a[0], a[1], b[0], b[1]))
    h = math.sin((la2 - la1) / 2) ** 2 + math.cos(la1) * math.cos(la2) * math.sin((lo2 - lo1) / 2) ** 2
    return 2 * R * math.asin(math.sqrt(h))


def features(region):
    t = pd.read_csv(DATA / f"tracts_{region}.csv", dtype={"geoid": str})
    acs = pd.read_csv(DATA / f"acs_{region}.csv", dtype={"geoid": str})
    lodes = pd.read_csv(DATA / f"lodes_{region}.csv", dtype={"geoid": str})
    osm = pd.read_csv(DATA / f"osm_counts_{region}.csv", dtype={"geoid": str})
    f = t.merge(acs, on="geoid", how="left").merge(lodes, on="geoid", how="left").merge(osm, on="geoid", how="left")
    osm_cols = [c for c in f.columns if c.startswith("osm_")]
    job_cols = [c for c in f.columns if c.startswith("jobs")]
    f[osm_cols + job_cols] = f[osm_cols + job_cols].fillna(0)
    f["area_km2"] = (f["aland_m2"] / 1e6).clip(lower=0.05)
    f["pop_k"] = f["pop"].fillna(0) / 1000
    f["jobs_k"] = f["jobs"] / 1000
    f["nocar_share"] = ((f["hh_owner_nocar"] + f["hh_renter_nocar"]) / f["hh"]).where(f["hh"] > 0)
    f["transit_share"] = (f["commute_transit"] / f["workers"]).where(f["workers"] > 0)
    f["taxi_share"] = (f["commute_taxi"] / f["workers"]).where(f["workers"] > 0)
    f["wfh_share"] = (f["commute_home"] / f["workers"]).where(f["workers"] > 0)
    f["log_income"] = np.log(f["med_income"].where(f["med_income"] > 0))
    f["km_center"] = [km((a, b), CENTER[region]) for a, b in zip(f["lat"], f["lng"])]
    f["km_airport"] = [km((a, b), AIRPORT[region]) for a, b in zip(f["lat"], f["lng"])]
    for c in osm_cols + ["jobs_k", "pop_k"] + [c for c in job_cols if c != "jobs"]:
        f[f"dens_{c}"] = f[c] / f["area_km2"]
    return f


def chicago_targets():
    p = pd.read_csv(DATA / "chicago_pickups_by_tract2020.csv.gz", dtype={"geoid": str})
    months = json.loads((ROOT / "jobs.json").read_text())["months"]
    days = pd.date_range(f"{months[0]}-01", pd.Timestamp(f"{months[-1]}-01") + pd.offsets.MonthEnd(0))
    ndow = {d: int(((days.dayofweek + 1) % 7 == d).sum()) for d in range(7)}  # pandas Mon=0 -> Socrata Sun=0
    rows = []
    for dt, dows in DAYTYPES.items():
        sub = p[p["dow"].isin(dows)].groupby(["geoid", "hh"], as_index=False)[["n", "sec", "mi", "fare", "tipped", "to_airport"]].sum()
        ndays = sum(ndow[d] for d in dows)
        sub["daytype"] = dt
        sub["per_hour"] = sub["n"] / ndays
        rows.append(sub)
    y = pd.concat(rows, ignore_index=True)
    y["avg_min"] = y["sec"] / y["n"] / 60
    y["avg_mi"] = y["mi"] / y["n"]
    y["airport_share"] = y["to_airport"] / y["n"]
    y["tip_share"] = y["tipped"] / y["n"]
    return y, ndow


def signatures(f, y):
    """NNLS per (daytype, hour): pickups/hour in a tract = sum over generators of count * beta."""
    X = f.set_index("geoid")[list(GENERATORS)].astype(float)
    out = []
    for (dt, hh), g in y.groupby(["daytype", "hh"]):
        g = g.set_index("geoid")["per_hour"]
        idx = X.index.intersection(g.index)
        A = X.loc[idx].values
        b = g.reindex(idx).fillna(0).values
        beta, _ = nnls(A, b)
        pred = A @ beta
        r2 = 1 - ((b - pred) ** 2).sum() / ((b - b.mean()) ** 2).sum()
        out.append({"daytype": dt, "hh": hh, "r2": round(r2, 3), **{GENERATORS[k]: round(v, 4) for k, v in zip(GENERATORS, beta)}})
    return pd.DataFrame(out)


def design(f, dt, hh_values):
    keep = ["km_center", "km_airport", "log_income", "nocar_share", "transit_share", "taxi_share", "wfh_share",
            "med_age", "area_km2"] + [c for c in f.columns if c.startswith("dens_")] + list(GENERATORS)
    base = f[["geoid"] + keep]
    frames = []
    for hh in hh_values:
        b = base.copy()
        b["hh"] = hh
        b["hh_sin"], b["hh_cos"] = math.sin(2 * math.pi * hh / 24), math.cos(2 * math.pi * hh / 24)
        for d in DAYTYPES:
            b[f"dt_{d}"] = int(d == dt)
        frames.append(b)
    return pd.concat(frames, ignore_index=True)


def main():
    OUT.mkdir(exist_ok=True)
    fc, fs = features("chicago"), features("seattle")
    y, ndow = chicago_targets()
    print("days per Socrata dow:", ndow)
    print("Chicago tracts with features:", len(fc), " with trips:", y["geoid"].nunique(), " rows:", len(y))

    sig = signatures(fc, y)
    sig.to_csv(OUT / "signatures.csv", index=False)
    print(sig[sig["daytype"] == "mon_thu"].to_string(index=False))

    # predictive model with spatial CV (folds = groups of tracts by county-subdivision proxy: first 9 digits)
    from sklearn.ensemble import HistGradientBoostingRegressor
    from sklearn.model_selection import GroupKFold
    data = []
    for dt in DAYTYPES:
        X = design(fc, dt, range(24))
        t = y[y["daytype"] == dt][["geoid", "hh", "per_hour", "airport_share", "avg_min", "avg_mi"]]
        data.append(X.merge(t, on=["geoid", "hh"], how="left").fillna({"per_hour": 0}))
    D = pd.concat(data, ignore_index=True)
    feat_cols = [c for c in D.columns if c not in ("geoid", "per_hour", "airport_share", "avg_min", "avg_mi")]
    target = np.log1p(D["per_hour"].values)
    # spatial blocks about 3 km square, so a held-out tract's neighbours are held out with it
    cell = fc.set_index("geoid").apply(lambda r: f"{math.floor(r['lat'] / 0.027)}_{math.floor(r['lng'] / 0.036)}", axis=1)
    groups = D["geoid"].map(cell).values
    print("spatial CV blocks:", len(set(groups)))
    cv = []
    for tr, te in GroupKFold(n_splits=5).split(D, target, groups):
        m = HistGradientBoostingRegressor(max_iter=400, learning_rate=0.06, max_leaf_nodes=31, l2_regularization=1.0)
        m.fit(D.iloc[tr][feat_cols], target[tr])
        p = m.predict(D.iloc[te][feat_cols])
        ss = ((target[te] - target[te].mean()) ** 2).sum()
        cv.append({"r2_log": 1 - ((target[te] - p) ** 2).sum() / ss,
                   "spearman_tract_total": float(pd.Series(np.expm1(p)).groupby(D.iloc[te]["geoid"].values).sum().corr(
                       pd.Series(D.iloc[te]["per_hour"].values).groupby(D.iloc[te]["geoid"].values).sum(), method="spearman"))})
    print("spatial CV:", cv)
    (OUT / "cv.json").write_text(json.dumps(cv, indent=1))

    model = HistGradientBoostingRegressor(max_iter=400, learning_rate=0.06, max_leaf_nodes=31, l2_regularization=1.0)
    model.fit(D[feat_cols], target)
    # airport share model (weighted by trips)
    A = D[D["per_hour"] > 0]
    am = HistGradientBoostingRegressor(max_iter=300, learning_rate=0.06, max_leaf_nodes=31)
    am.fit(A[feat_cols], A["airport_share"].fillna(0), sample_weight=A["per_hour"])

    preds = []
    for dt in DAYTYPES:
        X = design(fs, dt, range(24))
        X["pickups_per_hour"] = np.expm1(model.predict(X[feat_cols])).clip(min=0)
        X["airport_share"] = am.predict(X[feat_cols]).clip(0, 1)
        X["daytype"] = dt
        preds.append(X[["geoid", "daytype", "hh", "pickups_per_hour", "airport_share"]])
    P = pd.concat(preds, ignore_index=True)
    P.round(4).to_csv(OUT / "seattle_pred.csv.gz", index=False)
    print("wrote", OUT / "seattle_pred.csv.gz", len(P))


if __name__ == "__main__":
    main()
